// Assemble each TypeScript benchmark into one self-contained entry file for
// bento's AOT compiler.
//
//   node scripts/build-ts.mjs
//
// The benchmarks live one per file in ts/ and share the measurement harness in
// ts/harness.ts. They are concatenated rather than imported because bento's AOT
// lowerer does not yet cover two things a multi-file program needs: a top-level
// binding a sibling module does not export, and `export class`. Both are bento
// bugs worth fixing, but neither changes what the benchmark measures, so the
// concatenation keeps the ports readable in the meantime.

import { readFileSync, writeFileSync, mkdirSync } from "fs";
import { dirname, join } from "path";
import { fileURLToPath } from "url";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const src = join(root, "ts");
const out = join(root, "ts-dist");

// Each entry names the benchmark, its reference time from v8-v7/base.js (the
// score is 100 * reference / usec-per-iteration), the function to measure, and
// the setup and tear-down calls base.js runs outside the timing when the
// benchmark has them. A suite made of two benchmarks under one reference time,
// which is Crypto, carries a second entry and is scored off the geometric mean
// of the two, the way base.js scores a multi-benchmark suite.
export const BENCHES = [
  { name: "Richards", file: "richards", reference: 35302, entry: "runRichards()" },
  { name: "DeltaBlue", file: "deltablue", reference: 66118, entry: "deltaBlue()" },
  { name: "Crypto", file: "crypto", reference: 266181, entry: "runEncrypt()", entry2: "runDecrypt()", setup: "cryptoSetup()" },
  { name: "RayTrace", file: "raytrace", reference: 739989, entry: "renderScene()" },
  { name: "EarleyBoyer", file: "earley-boyer", reference: 667063, entry: "runEarleyBoyer()" },
  { name: "RegExp", file: "regexp", reference: 910985, entry: "runRegExpBenchmark()", setup: "regExpSetup()", tearDown: "regExpTearDown()" },
  { name: "Splay", file: "splay", reference: 81491, entry: "runSplay()", setup: "splaySetup()", tearDown: "splayTearDown()" },
  { name: "NavierStokes", file: "navier-stokes", reference: 1484000, entry: "runNavierStokes()", setup: "navierStokesSetup()", tearDown: "navierStokesTearDown()" },
];

// strip removes the import and export keywords the split-file sources carry so
// the concatenated file is one module with one set of top-level bindings.
function strip(text) {
  return text
    .split("\n")
    .filter((line) => !/^import\s/.test(line))
    .map((line) => line.replace(/^export (?=(const|let|var|function|class|abstract|async) )/, ""))
    .join("\n");
}

function main() {
  mkdirSync(out, { recursive: true });
  const harness = strip(readFileSync(join(src, "harness.ts"), "utf8"));
  const built = [];
  for (const b of BENCHES) {
    let body;
    try {
      body = readFileSync(join(src, `${b.file}.ts`), "utf8");
    } catch {
      continue; // not ported yet
    }
    const text = [
      `// Generated by scripts/build-ts.mjs from ts/harness.ts and ts/${b.file}.ts.`,
      "// Edit those, not this file.",
      "",
      harness,
      strip(body),
      "",
      ...(b.entry2
        ? [
            `runPair(${JSON.stringify(b.name)}, ${b.reference},`,
            `  () => { ${b.setup ?? ""} },`,
            `  () => { ${b.entry}; },`,
            `  () => { ${b.entry2}; },`,
            `  () => { ${b.tearDown ?? ""} });`,
          ]
        : [
            `run(${JSON.stringify(b.name)}, ${b.reference},`,
            `  () => { ${b.setup ?? ""} },`,
            `  () => { ${b.entry}; },`,
            `  () => { ${b.tearDown ?? ""} });`,
          ]),
      "",
      // Without this the file is a script, not a module, so its top-level names
      // share the global scope and a class named after a lib global (Scheduler,
      // Event, Range) is a duplicate identifier before it ever reaches lowering.
      "export const __module = 0; // makes this a module, not a global script",
      "",
    ].join("\n");
    writeFileSync(join(out, `${b.file}.ts`), text);
    built.push(b.file);
  }
  console.log(`wrote ${built.length} entries to ts-dist: ${built.join(", ")}`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
