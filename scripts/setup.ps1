# The Windows half of scripts/setup.sh. Installs the engines this benchmark
# needs on a machine we own, the way the GitHub action installs them on a
# runner. Safe to re-run: everything here skips work that is already done.
#
#   pwsh -File scripts/setup.ps1          # bento, v8, bun, node, quickjs
#   pwsh -File scripts/setup.ps1 -All     # plus every other engine ei can fetch
#
# Afterwards, dot-source scripts/env.ps1 (written by this script) to put the
# installed binaries on PATH, then run scripts/bench.mjs.
param([switch]$All)

$ErrorActionPreference = "Stop"

$root = Split-Path -Parent $PSScriptRoot
$eiDir = Join-Path $HOME ".ei"
$bunDir = Join-Path $HOME ".bun\bin"
$binDir = Join-Path $HOME "bin"

$env:PATH = "$eiDir;$bunDir;$binDir;$env:PATH"

function Have($name) {
  return $null -ne (Get-Command $name -ErrorAction SilentlyContinue)
}

Write-Host "==> easy-install"
if (-not (Have "ei")) {
  Invoke-RestMethod https://raw.githubusercontent.com/easy-install/easy-install/main/install.ps1 | Invoke-Expression
  $env:PATH = "$eiDir;$env:PATH"
}

Write-Host "==> node"
if (-not (Have "node")) {
  throw "node is not installed. Install it from https://nodejs.org and re-run."
}

Write-Host "==> bun"
if (-not (Have "bun")) {
  Invoke-RestMethod bun.sh/install.ps1 | Invoke-Expression
  $env:PATH = "$bunDir;$env:PATH"
}

Write-Host "==> bento"
if (Have "bento") {
  Write-Host "already installed: $((Get-Command bento).Source)"
} elseif (-not (Have "go")) {
  Write-Warning "go is not installed; skipping bento. Install Go, then re-run."
} else {
  # Built from a checkout, not go install: bento's go.mod carries a replace
  # directive, which makes it uninstallable that way. Point BENTO_SRC at a
  # local checkout to benchmark that instead of the published tip.
  New-Item -ItemType Directory -Force -Path $binDir | Out-Null
  $src = $env:BENTO_SRC
  if (-not $src) {
    $src = Join-Path ([System.IO.Path]::GetTempPath()) "bento-src"
    if (Test-Path $src) { Remove-Item -Recurse -Force $src }
    git clone --depth 1 https://github.com/tamnd/bento $src
  }
  Push-Location $src
  $env:CGO_ENABLED = "0"
  go build -o (Join-Path $binDir "bento.exe") ./cmd/bento
  Pop-Location
}

Write-Host "==> v8 and quickjs"
ei https://github.com/ahaoboy/v8-build
ei https://github.com/ahaoboy/quickjs-build

if ($All) {
  Write-Host "==> the rest"
  $urls = @(
    "https://github.com/boa-dev/boa",
    "https://github.com/facebook/hermes",
    "https://github.com/ahaoboy/txiki.js-build",
    "https://github.com/ahaoboy/spidermonkey-build",
    "https://github.com/ahaoboy/mujs-build",
    "https://github.com/ahaoboy/rquickjs-cli",
    "https://github.com/ahaoboy/ChakraCore-build",
    "https://github.com/ahaoboy/goja-build",
    "https://github.com/ahaoboy/duktape-build",
    "https://github.com/ahaoboy/njs-build",
    "https://github.com/ahaoboy/bare-build"
  )
  foreach ($url in $urls) {
    Write-Host "install: $url"
    try { ei $url } catch { Write-Warning "failed: $url" }
  }
}

# One place for callers to pick up every install location, since ei scatters
# each engine into its own directory.
$dirs = @($eiDir, $bunDir, $binDir)
if (Test-Path $eiDir) {
  $dirs += (Get-ChildItem -Path $eiDir -Directory | ForEach-Object { $_.FullName })
}
$envPs1 = Join-Path $root "scripts\env.ps1"
@(
  "# Generated by scripts/setup.ps1. Dot-source this before running scripts/bench.mjs.",
  "`$env:PATH = `"$($dirs -join ';');`$env:PATH`""
) | Set-Content -Path $envPs1

Write-Host ""
Write-Host "wrote $envPs1"
Write-Host "next: . $envPs1; node scripts/bench.mjs --engines bento,v8,bun,node,quickjs --repeat 3"
