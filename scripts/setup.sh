#!/usr/bin/env bash
# Install the engines this benchmark needs on a machine we own, the way the
# GitHub action installs them on a runner. Safe to re-run: everything here
# skips work that is already done.
#
#   bash scripts/setup.sh              # bento, v8, bun, node, quickjs
#   bash scripts/setup.sh --all        # plus every other engine ei can fetch
#
# Afterwards, source scripts/env.sh (written by this script) to put the
# installed binaries on PATH, then run scripts/bench.mjs.
set -euo pipefail

ALL=0
[ "${1:-}" = "--all" ] && ALL=1

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
EI_DIR="$HOME/.ei"
BUN_DIR="$HOME/.bun/bin"
NODE_DIR="$HOME/.local/node/bin"
GOBIN="${GOBIN:-$HOME/bin}"

export PATH="$EI_DIR:$EI_DIR/v8:$EI_DIR/qjs:$BUN_DIR:$NODE_DIR:$GOBIN:$PATH"

have() { command -v "$1" >/dev/null 2>&1; }

echo "==> easy-install"
if ! have ei; then
  curl -fsSL https://raw.githubusercontent.com/easy-install/easy-install/main/install.sh | bash
fi

echo "==> node"
if ! have node; then
  # The tarball keeps this independent of whatever package manager the box has.
  case "$(uname -s)" in
    Darwin) NODE_OS=darwin ;;
    *) NODE_OS=linux ;;
  esac
  case "$(uname -m)" in
    arm64 | aarch64) NODE_ARCH=arm64 ;;
    *) NODE_ARCH=x64 ;;
  esac
  NODE_VER=v24.11.0
  mkdir -p "$HOME/.local"
  curl -fsSL "https://nodejs.org/dist/$NODE_VER/node-$NODE_VER-$NODE_OS-$NODE_ARCH.tar.xz" |
    tar -xJ -C "$HOME/.local"
  rm -rf "$HOME/.local/node"
  mv "$HOME/.local/node-$NODE_VER-$NODE_OS-$NODE_ARCH" "$HOME/.local/node"
fi

echo "==> bun"
have bun || curl -fsSL https://bun.sh/install | bash

echo "==> bento"
if ! have go; then
  echo "go is not installed; skipping bento. Install Go, then re-run." >&2
else
  # Built from source rather than fetched, so a local bento checkout can be
  # benchmarked by pointing BENTO_SRC at it.
  if [ -n "${BENTO_SRC:-}" ]; then
    (cd "$BENTO_SRC" && CGO_ENABLED=0 go build -o "$GOBIN/bento" ./cmd/bento)
  else
    CGO_ENABLED=0 GOBIN="$GOBIN" go install github.com/tamnd/bento/cmd/bento@latest
  fi
fi

echo "==> v8 and quickjs"
ei https://github.com/ahaoboy/v8-build
ei https://github.com/ahaoboy/quickjs-build

if [ "$ALL" = 1 ]; then
  echo "==> the rest"
  for url in \
    https://github.com/boa-dev/boa \
    https://github.com/facebook/hermes \
    https://github.com/ahaoboy/txiki.js-build \
    https://github.com/ahaoboy/spidermonkey-build \
    https://github.com/ahaoboy/mujs-build \
    https://github.com/ahaoboy/rquickjs-cli \
    https://github.com/ahaoboy/ChakraCore-build \
    https://github.com/ahaoboy/goja-build \
    https://github.com/ahaoboy/duktape-build \
    https://github.com/ahaoboy/njs-build \
    https://github.com/ahaoboy/bare-build; do
    echo "install: $url"
    ei "$url" || echo "failed: $url" >&2
  done
  ei https://github.com/quickjs-ng/quickjs --name qjs --alias qjs-ng || true
fi

# One place for callers to pick up every install location, since ei scatters
# each engine into its own directory.
ENV_SH="$ROOT/scripts/env.sh"
{
  echo "# Generated by scripts/setup.sh. Source this before running scripts/bench.mjs."
  printf 'export PATH="%s"\n' "$(
    printf '%s' "$EI_DIR:$BUN_DIR:$NODE_DIR:$GOBIN"
    for d in "$EI_DIR"/*/; do
      [ -d "$d" ] && printf ':%s' "${d%/}"
    done
    printf ':$PATH'
  )"
} >"$ENV_SH"

echo
echo "wrote $ENV_SH"
echo "next: source $ENV_SH && node scripts/bench.mjs --engines bento,v8,bun,node,quickjs --repeat 3"
